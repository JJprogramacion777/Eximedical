-- ---------- Productos de la tienda ----------
create table if not exists productos (
  id          bigint generated by default as identity primary key,
  slug        text not null unique,
  name        text not null,
  category    text not null check (category in ('equipos-medicos', 'mobiliario', 'instrumental-quirurgico', 'descartables', 'anatomicos')),
  description text not null default '',
  images      text[] not null default '{}',
  active      boolean not null default true,
  featured    boolean not null default false,
  sort        integer not null default 0,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create index if not exists productos_category_idx on productos (category);

-- ---------- Catálogos PDF ----------
create table if not exists catalogos (
  id          bigint generated by default as identity primary key,
  slug        text not null unique,
  title       text not null,
  description text not null default '',
  img         text not null default '',
  pdf         text not null default '',
  size        text not null default '',
  "group"     text not null default 'Equipamiento' check ("group" in ('Equipamiento', 'Insumos', 'Especialidades')),
  featured    boolean not null default false,
  active      boolean not null default true,
  sort        integer not null default 0,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

-- ---------- Administradores del panel ----------
create table if not exists admin_users (
  id            bigint generated by default as identity primary key,
  email         text not null unique,
  name          text not null default '',
  password_hash text not null,
  created_at    timestamptz not null default now(),
  last_login_at timestamptz
);

-- ---------- updated_at automático ----------
create or replace function set_updated_at() returns trigger
language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end $$;

drop trigger if exists productos_updated_at on productos;
create trigger productos_updated_at before update on productos
  for each row execute function set_updated_at();

drop trigger if exists catalogos_updated_at on catalogos;
create trigger catalogos_updated_at before update on catalogos
  for each row execute function set_updated_at();
